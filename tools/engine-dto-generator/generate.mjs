import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { InputData, JSONSchemaInput, quicktype } from "quicktype-core";

const toolDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(toolDirectory, "..", "..");
const openApiPath = resolve(repositoryRoot, "protocol", "runtime-v1.openapi.json");

const outputs = [
	{
		lang: "csharp",
		path: resolve(
			repositoryRoot,
			"engines",
			"godot",
			"csharp",
			"src",
			"OpenGameAgent.Protocol",
			"Generated",
			"RuntimeProtocol.g.cs",
		),
		filename: "RuntimeProtocol.g.cs",
		rendererOptions: {
			framework: "SystemTextJson",
			features: "attributes-only",
			namespace: "OpenGameAgent.Protocol",
			"csharp-version": "8",
			"any-type": "object",
			"check-required": "true",
			"dateonly-timeonly-converters": "false",
		},
	},
	{
		lang: "csharp",
		path: resolve(
			repositoryRoot,
			"engines",
			"unity",
			"Packages",
			"com.opengameagent.client",
			"Runtime",
			"Generated",
			"RuntimeProtocol.g.cs",
		),
		filename: "RuntimeProtocol.g.cs",
		rendererOptions: {
			framework: "NewtonSoft",
			features: "complete",
			namespace: "OpenGameAgent.Unity.Protocol",
			"csharp-version": "8",
			"any-type": "object",
			"check-required": "true",
		},
	},
];

const openApi = JSON.parse(await readFile(openApiPath, "utf8"));
const componentSchemas = openApi.components?.schemas;
if (!componentSchemas || typeof componentSchemas !== "object" || Array.isArray(componentSchemas)) {
	throw new Error("Runtime OpenAPI document has no component schemas.");
}

const names = Object.keys(componentSchemas).sort();
if (names.length === 0) throw new Error("Runtime OpenAPI document has no named schemas.");

const schema = {
	$schema: "http://json-schema.org/draft-07/schema#",
	title: "RuntimeProtocol",
	type: "object",
	definitions: rewriteReferences(componentSchemas),
	properties: Object.fromEntries(names.map((name) => [name, { $ref: `#/definitions/${name}` }])),
	required: names,
	additionalProperties: false,
};

for (const output of outputs) {
	const schemaInput = new JSONSchemaInput(undefined);
	await schemaInput.addSource({ name: "RuntimeProtocol", schema: JSON.stringify(schema) });
	const inputData = new InputData();
	inputData.addInput(schemaInput);

	const result = await quicktype({
		inputData,
		lang: output.lang,
		outputFilename: output.filename,
		rendererOptions: output.rendererOptions,
		alphabetizeProperties: true,
		fixedTopLevels: true,
	});

	const notice =
		"// <auto-generated />\n// Generated from protocol/runtime-v1.openapi.json. Do not edit.\n#nullable enable\n#pragma warning disable CS8602, CS8610, CS8618\n\n";
	const content = `${notice}${result.lines.join("\n")}\n`;
	await mkdir(dirname(output.path), { recursive: true });
	await writeFile(output.path, content, "utf8");
}

console.log(`Generated engine Runtime Protocol DTOs (${outputs.length} artifacts, ${names.length} schemas).`);

function rewriteReferences(value) {
	if (Array.isArray(value)) return value.map(rewriteReferences);
	if (value === null || typeof value !== "object") return value;

	return Object.fromEntries(
		Object.entries(value).map(([key, child]) => [
			key,
			key === "$ref" && typeof child === "string"
				? child.replace("#/components/schemas/", "#/definitions/")
				: rewriteReferences(child),
		]),
	);
}
